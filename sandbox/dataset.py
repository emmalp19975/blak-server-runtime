    print(f" File Size:           {info['file_size_mb']} MB ({info['file_size_bytes']} bytes)")
    print(f" Ready for Training:  {'YES (Ready for Neural Net Training!)' if info['is_ready_for_training'] else 'ACCUMULATING (Keep collecting data)'}")
    print("\n Dataset Breakdown:")
