"""
sandbox/dataset.py
==================
Machine Learning Dataset Loader & Feature Vectorizer for Blak.

Converts JSONL match records generated by GameRecorder into numerical
tensors/arrays suitable for Supervised Policy Learning, Value Networks,
and Reinforcement Learning agents (PyTorch / NumPy compatible).
"""

from __future__ import annotations
import json
import os
from typing import Any, Dict, Generator, List, Optional, Tuple


class BlakTransition:
    """A single state-action-outcome transition for ML training."""

    def __init__(
        self,
        state_features: List[float],
        action_type: str,
        action_class: int,
        slot_target: int,
        discard_target: int,
        reward: float,
        match_outcome: float,
        metadata: Dict[str, Any],
    ) -> None:
        self.state_features = state_features
        self.action_type = action_type
        self.action_class = action_class
        self.slot_target = slot_target
        self.discard_target = discard_target
        self.reward = reward
        self.match_outcome = match_outcome  # +1.0 (Win) or -1.0 (Loss)
        self.metadata = metadata


class BlakDataset:
    """
    Parses matches.jsonl and extracts vectorized feature representations.
    """

    ACTION_MAP = {
        "hand": 0,
        "play_hand": 0,
        "play_card": 0,
        "objective": 1,
        "play_objective": 1,
        "discard_play": 2,
        "play_discard": 2,
        "opponent_objective": 3,
        "play_opp_objective": 3,
        "perk": 4,
        "initiate_ladder_perk": 4,
        "discard": 5,
        "discard_card": 5,
        "fallback_discard": 5,
        "end_turn": 5,
        "decline_perk": 6,
        "decline_ladder_perk": 6,
    }

    def __init__(self, filepath: str = "data/training_data/matches.jsonl") -> None:
        self.filepath = filepath
        self.transitions: List[BlakTransition] = []
        if os.path.exists(filepath):
            self.load()

    def load(self) -> None:
        """Loads and parses all matches in the JSONL file."""
        self.transitions.clear()
        with open(self.filepath, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                match = json.loads(line)
                self._parse_match(match)

    def _parse_match(self, match: Dict[str, Any]) -> None:
        match_id = match.get("match_id", "")
        seed = match.get("seed", 0)

        for turn in match.get("turns", []):
            turn_num = turn.get("turn_number", 0)
            player_id = turn.get("player_id", "")

            for step in turn.get("steps", []):
                state = step.get("state", {})
                action = step.get("action", {})
                reward = float(step.get("reward", 0.0))
                outcome = float(step.get("match_outcome", 0.0))

                features = self.vectorize_state(state)
                a_type = action.get("type", "unknown")
                a_class = self.ACTION_MAP.get(a_type, 5)  # default to discard if unknown

                slot_idx = int(action.get("slot_index", 0)) if action.get("slot_index") is not None else 0
                slot_target = max(0, min(3, slot_idx))

                disc_idx = int(action.get("discard_slot_index", 0)) if action.get("discard_slot_index") is not None else 0
                disc_target = max(0, min(3, disc_idx))

                meta = {
                    "match_id": match_id,
                    "seed": seed,
                    "turn": turn_num,
                    "player": player_id,
                    "action_details": action,
                }

                self.transitions.append(
                    BlakTransition(
                        state_features=features,
                        action_type=a_type,
                        action_class=a_class,
                        slot_target=slot_target,
                        discard_target=disc_target,
                        reward=reward,
                        match_outcome=outcome,
                        metadata=meta,
                    )
                )

    @classmethod
    def vectorize_state(cls, state: Dict[str, Any], player_id: Optional[str] = None) -> List[float]:
        """
        Transforms raw state snapshot into a fixed-length numerical feature vector (128 dimensions).
        Handles both flat recorded states and nested engine sanitized states.
        """
        feats: List[float] = []

        # Unpack nested player data if coming from engine.get_sanitized_state_for_player
        players_dict = state.get("players")
        active_p = player_id or state.get("active_player", "")
        if players_dict and isinstance(players_dict, dict):
            p_data = players_dict.get(active_p)
            if not p_data:
                for pid, pdata in players_dict.items():
                    if "hand" in pdata:
                        p_data = pdata
                        active_p = pid
                        break
            if p_data:
                hand = p_data.get("hand", [])
                discard_piles = p_data.get("discard_piles", [[], [], [], []])
                top_obj = p_data.get("objective_top_card", {})
                obj_rem = p_data.get("objective_remaining", 0)
                opponents = []
                for opid, opdata in players_dict.items():
                    if opid != active_p:
                        opponents.append({
                            "id": opid,
                            "objective_remaining": opdata.get("objective_remaining", 0),
                            "objective_top": opdata.get("objective_top_card", {}),
                            "discard_tops": opdata.get("discard_pile", []),
                        })
            else:
                hand = state.get("hand", [])
                discard_piles = state.get("discard_piles", [[], [], [], []])
                top_obj = state.get("objective_top_card", {})
                obj_rem = state.get("objective_remaining", 0)
                opponents = state.get("opponents", [])
        else:
            hand = state.get("hand", [])
            discard_piles = state.get("discard_piles", [[], [], [], []])
            top_obj = state.get("objective_top_card", {})
            obj_rem = state.get("objective_remaining", 0)
            opponents = state.get("opponents", [])

        # 1. Board Slots (4 slots * 4 features = 16 floats)
        # [value / 12.0, is_omni, pending_perk, cards_count / 12.0]
        board = state.get("board", [])
        for i in range(4):
            if i < len(board):
                s = board[i]
                feats.append(float(s.get("value", 0)) / 12.0)
                feats.append(1.0 if s.get("is_omni", False) else 0.0)
                feats.append(1.0 if s.get("pending_perk", False) else 0.0)
                feats.append(float(s.get("cards_count", 0)) / 12.0)
            else:
                feats.extend([0.0, 0.0, 0.0, 0.0])

        # 2. Hand Histogram (14 floats: Jokers + numbers 1..12 + hand_size/5.0)
        hand_counts = [0.0] * 13  # 0=Joker, 1..12=Numbers
        for c in hand:
            if c.get("type") == "joker":
                hand_counts[0] += 1.0
            else:
                val = max(1, min(int(c.get("value", 0)), 12))
                hand_counts[val] += 1.0
        feats.extend([c / 5.0 for c in hand_counts])
        feats.append(len(hand) / 5.0)

        # 3. Discard Piles Tops (4 slots * 13 floats = 52 floats one-hot)
        for s_idx in range(4):
            slot_onehot = [0.0] * 13
            if s_idx < len(discard_piles) and discard_piles[s_idx]:
                top = discard_piles[s_idx][-1]
                if top.get("type") == "joker":
                    slot_onehot[0] = 1.0
                else:
                    val = max(1, min(int(top.get("value", 0)), 12))
                    slot_onehot[val] = 1.0
            feats.extend(slot_onehot)

        # 4. Objective (14 floats: one-hot of top card + remaining count normalized)
        obj_onehot = [0.0] * 13
        if top_obj:
            if top_obj.get("type") == "joker":
                obj_onehot[0] = 1.0
            elif top_obj.get("type") == "number":
                val = max(1, min(int(top_obj.get("value", 0)), 12))
                obj_onehot[val] = 1.0
        feats.extend(obj_onehot)
        feats.append(float(obj_rem) / 16.0)

        # 5. Turn Context (2 floats)
        feats.append(float(state.get("discards_this_turn", 0)) / 2.0)
        feats.append(float(state.get("main_deck_size", 0)) / 162.0)

        # 6. Visible Opponent Summaries (up to 3 opponents * 10 floats = 30 floats)
        opponents = opponents if opponents else state.get("opponents", [])
        for o_idx in range(3):
            if o_idx < len(opponents):
                opp = opponents[o_idx]
                feats.append(float(opp.get("objective_remaining", 0)) / 16.0)
                opp_top = opp.get("objective_top", {})
                opp_val = float(opp_top.get("value", 0)) if opp_top.get("type") == "number" else 0.0
                feats.append(opp_val / 12.0)
                # 4 discard tops normalized
                d_tops = {d.get("slot_index", i): d for i, d in enumerate(opp.get("discard_tops", []))}
                for ds in range(4):
                    d_card = d_tops.get(ds, {})
                    c_val = float(d_card.get("value", 0)) if d_card.get("type") == "number" else 0.0
                    feats.append(c_val / 12.0)
                # 4 padding floats
                feats.extend([0.0, 0.0, 0.0, 0.0])
            else:
                feats.extend([0.0] * 10)

        # Ensure exact 128 dimension length
        if len(feats) < 128:
            feats.extend([0.0] * (128 - len(feats)))
        return feats[:128]

    def __len__(self) -> int:
        return len(self.transitions)

    def __getitem__(self, idx: int) -> Tuple[List[float], int, int, int, float]:
        """
        Returns (state_feature_vector, action_class_target, slot_target, discard_target, value_target).
        """
        t = self.transitions[idx]
        return (t.state_features, t.action_class, t.slot_target, t.discard_target, t.match_outcome)

    def stats(self) -> Dict[str, Any]:
        """Calculates dataset metrics."""
        action_dist: Dict[str, int] = {}
        outcomes = [t.match_outcome for t in self.transitions]
        for t in self.transitions:
            action_dist[t.action_type] = action_dist.get(t.action_type, 0) + 1

        wins = sum(1 for o in outcomes if o > 0)
        losses = sum(1 for o in outcomes if o < 0)

        return {
            "total_samples": len(self.transitions),
            "feature_dim": 128,
            "action_distribution": action_dist,
            "wins": wins,
            "losses": losses,
        }


def get_dataset_size(
    filepath: str = "data/training_data/matches.jsonl",
    target_training_samples: int = 50_000,
) -> Dict[str, Any]:
    """
    Returns comprehensive metrics on the current training dataset size,
    breakdowns by source and defeated opponent tags, and training readiness.
    """
    if not os.path.exists(filepath):
        return {
            "exists": False,
            "filepath": filepath,
            "matches_count": 0,
            "transitions_count": 0,
            "file_size_bytes": 0,
            "file_size_mb": 0.0,
            "is_ready_for_training": False,
            "progress_percent": 0.0,
            "target_training_samples": target_training_samples,
            "breakdown": {
                "source": {"simulation": 0, "production": 0},
                "match_type": {"pvp": 0, "bot_self_play": 0, "mixed": 0},
                "winner_defeated": {"human": 0, "dumbot": 0, "human_and_dumbot": 0, "none": 0},
            },
        }

    file_size_bytes = os.path.getsize(filepath)
    file_size_mb = file_size_bytes / (1024.0 * 1024.0)

    matches_count = 0
    transitions_count = 0
    source_counts: Dict[str, int] = {}
    type_counts: Dict[str, int] = {}
    defeated_counts: Dict[str, int] = {}

    with open(filepath, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            matches_count += 1
            try:
                m = json.loads(line)
                src = m.get("source", "unknown")
                source_counts[src] = source_counts.get(src, 0) + 1

                m_type = m.get("match_type", "unknown")
                type_counts[m_type] = type_counts.get(m_type, 0) + 1

                def_tag = m.get("winner_defeated", "none")
                defeated_counts[def_tag] = defeated_counts.get(def_tag, 0) + 1

                for turn in m.get("turns", []):
                    transitions_count += len(turn.get("steps", []))
            except Exception:
                pass

    progress = min(100.0, (transitions_count / max(1, target_training_samples)) * 100.0)
    is_ready = transitions_count >= target_training_samples

    return {
        "exists": True,
        "filepath": filepath,
        "matches_count": matches_count,
        "transitions_count": transitions_count,
        "file_size_bytes": file_size_bytes,
        "file_size_mb": round(file_size_mb, 2),
        "is_ready_for_training": is_ready,
        "progress_percent": round(progress, 1),
        "target_training_samples": target_training_samples,
        "breakdown": {
            "source": source_counts,
            "match_type": type_counts,
            "winner_defeated": defeated_counts,
        },
    }


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Inspect Blak Training Dataset Size")
    parser.add_argument("--file", type=str, default="data/training_data/matches.jsonl", help="Dataset path")
    parser.add_argument("--target", type=int, default=50_000, help="Target samples for training readiness")
    args = parser.parse_args()

    info = get_dataset_size(filepath=args.file, target_training_samples=args.target)
    print("\n=======================================================")
    print(" Blak AI Training Dataset Status")
